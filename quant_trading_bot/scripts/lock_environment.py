"""Pin the installed transitive dependency closure without copying unrelated packages."""
from importlib import metadata
from pathlib import Path
import sys
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
roots = ["numpy", "pandas", "pyarrow", "scipy", "scikit-learn", "pydantic", "PyYAML", "joblib", "tzdata", "requests", "lightgbm", "gymnasium", "pytest", "streamlit", "xgboost", "optuna", "duckdb", "plotly", "databento"]
advanced = "--advanced" in sys.argv
if advanced:
    roots += ["torch", "stable-baselines3"]
queue, versions = list(roots), {}
while queue:
    name = canonicalize_name(queue.pop())
    if name in versions:
        continue
    dist = metadata.distribution(name)
    versions[name] = dist.version
    for text in dist.requires or []:
        req = Requirement(text)
        if req.marker is None or req.marker.evaluate({"extra": ""}):
            queue.append(req.name)
lines = ["# Installed/tested transitive closure on Windows Python 3.13; generated by scripts/lock_environment.py.",
         "# CPU neural models use the separately documented optional torch dependency."]
for name, version in sorted(versions.items()):
    marker = "; sys_platform == 'win32'" if name in ("colorama", "pywin32") else ""
    lines.append(f"{name}=={version}{marker}")
(ROOT/("requirements-advanced.lock" if advanced else "requirements.lock")).write_text("\n".join(lines)+"\n", encoding="utf-8")
print(f"Pinned {len(versions)} packages; clean installation still requires free disk and registry availability.")
